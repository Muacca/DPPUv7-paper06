def derive_fixed_shape():
    """Fixed-shape torus constraint with lapse retained."""
    ck = Identities()
    A, q, N, q0, N0, VOL = s.symbols('A q N q0 N0 volume', positive=True)
    qd, qdd, Nd, p = s.symbols('qd qdd Nd p', real=True)
    dt = lambda f: s.diff(f, q) * qd + s.diff(f, qd) * qdd + s.diff(f, N) * Nd
    L = -A * q * qd ** 2 / N
    Eq = simp(s.diff(L, q) - dt(s.diff(L, qd)))
    EN = simp(s.diff(L, N))
    pq = s.diff(L, qd)
    C = -p ** 2 / (4 * A * q)
    H = N * C
    ck.zero('Euler_q', Eq - A * (qd ** 2 / N + 2 * q * qdd / N - 2 * q * qd * Nd / N ** 2))
    ck.zero('Euler_N', EN - A * q * qd ** 2 / N ** 2)
    ck.zero('Legendre_Hamiltonian', (p * qd - L).subs(qd, -N * p / (2 * A * q)) - H)
    ck.zero('Noether_identity', qd * Eq - N * dt(EN))
    ck.zero('exact_static_Euler', [Eq.subs({qd: 0, qdd: 0}), EN.subs(qd, 0)])
    flow = s.Matrix([s.diff(C, p), -s.diff(C, q)])
    ck.zero('Hamilton_flow_on_shell', flow.subs(p, 0))
    ck.zero('constraint_gradient_on_shell', s.Matrix([s.diff(C, q), s.diff(C, p)]).subs(p, 0))
    ck.zero('constraint_nonzero_transverse_Hessian', s.diff(C, p, 2) + 1 / (2 * A * q))
    ck.zero('regularized_generator_p', s.Matrix([s.diff(p, p), -s.diff(p, q)]) - s.Matrix([1, 0]))
    ep = s.Symbol('epsilon', real=True)
    u, ud, udd, v, vd, vdd, m, md, l, ld, N0d = s.symbols('u ud udd v vd vdd m md lapse2 lapse2d N0d', real=True)
    sub = {q: q0 + ep * u + ep ** 2 * v, qd: ep * ud + ep ** 2 * vd, qdd: ep * udd + ep ** 2 * vdd, N: N0 + ep * m + ep ** 2 * l, Nd: N0d + ep * md + ep ** 2 * ld}
    coeff = lambda f, k: simp(s.series(f.subs(sub, simultaneous=True), ep, 0, k + 1).removeO().expand().coeff(ep, k))
    eq1 = coeff(Eq, 1)
    en1 = coeff(EN, 1)
    en2 = coeff(EN, 2)
    lag2 = coeff(L, 2)
    mom1 = coeff(pq, 1)
    ck.zero('first_order_radius', eq1 - 2 * A * q0 * (udd / N0 - ud * N0d / N0 ** 2))
    ck.zero('first_order_lapse_constraint_vanishes', en1)
    ck.zero('second_order_lapse_constraint', en2 - A * q0 * ud ** 2 / N0 ** 2)
    ck.zero('second_order_constraint_no_second_order_correction', [s.diff(en2, x) for x in (v, vd, vdd, l, ld, m, md)])
    ck.zero('quadratic_action', lag2 + A * q0 * ud ** 2 / N0)
    ck.zero('linear_momentum', mom1 + 2 * A * q0 * ud / N0)
    p1, p2 = s.symbols('p1 p2', real=True)
    c2 = simp(s.series(C.subs({q: q0 + ep * u + ep ** 2 * v, p: ep * p1 + ep ** 2 * p2}), ep, 0, 3).removeO().expand().coeff(ep, 2))
    ck.zero('second_order_Hamilton_constraint', c2 + p1 ** 2 / (4 * A * q0))
    ck.zero('Lagrange_Hamilton_constraint_equivalence', c2.subs(p1, mom1) + en2)
    a, b, tau = s.symbols('a b tau', real=True)
    u_sol = a + b * tau
    ck.zero('linear_solution_arbitrary_lapse', eq1.subs({ud: b * N0, udd: b * N0d}))
    ck.zero('linear_solution_second_order_obstruction', en2.subs(ud, b * N0) - A * q0 * b ** 2)
    ck.zero('integrable_constant_family', C.subs(p, 0))
    q_exact = q0 + ep * a
    ck.zero('constant_family_exact_Euler', Eq.subs({q: q_exact, qd: 0, qdd: 0}))
    ck.zero('constant_family_exact_constraint', EN.subs({q: q_exact, qd: 0}))
    jac = s.Matrix([[s.diff(u_sol, a), s.diff(u_sol, b)], [s.diff(-2 * A * q0 * b, a), s.diff(-2 * A * q0 * b, b)]])
    lin_omega = simp(jac.det())
    ck.zero('formal_linearized_symplectic_form', lin_omega + 2 * A * q0)
    ck.zero('fixed_lattice_volume_variation', s.diff(VOL * (q0 + ep * a) ** 3, ep).subs(ep, 0) - 3 * VOL * q0 ** 2 * a)
    t = s.Symbol('t', real=True)
    nf = s.Function('N0')(t)
    If = s.Function('I')(t)
    xi = If / nf
    ck.zero('zero_integral_lapse_variation_is_endpoint_gauge', s.diff(xi * nf, t) - s.diff(If, t))
    return dict(identities=ck.names, L=L, Euler_q=Eq, Euler_N=EN, momentum=pq, constraint=C, Hamilton_flow=flow, regularized_p_flow=[1, 0], linear_radius=eq1, linear_lapse=en1, quadratic_action=lag2, second_order_lapse=en2, second_order_constraint=c2, linear_solution=u_sol, obstruction=A * q0 * b * b, formal_linearized_omega_da_db=lin_omega, exact_solution='q=q0>0, p=0, N(t)>0 arbitrary; auxiliary torsion zero', integrable_variations='u=a; b=0 follows from second-order real lapse constraint', endpoint_conditions='Dirichlet q at both ends; gauge xi(t_i)=xi(t_f)=0', boundary_data='A solution exists only when prescribed endpoint q values agree. With fixed values q0 is fixed; q0 varies across boundary data.', lapse_modulus='For endpoint-preserving reparametrizations, T=integral N dt is invariant. At fixed T every zero-integral lapse variation is gauge; if T is not fixed it remains a global interval parameter.', presymplectic='Pullback of dq wedge dp plus dN wedge dp_N to exact solutions is zero. Its kernel includes q0 and, if varied, T, which are not generated by endpoint-preserving time reparametrization.', scope='Common-scale finite-dimensional truncation only; no full gravity spectrum or dynamical instability claim')

def derive_point_coordinates():
    """Positive canonical point transformation of the torus constraint."""
    ck = Identities()
    A, r, N, q = s.symbols('A r N q', positive=True)
    rd, rdd, Nd, pr, pq = s.symbols('rd rdd Nd pr pq', real=True)
    qofr = r ** s.Rational(2, 3)
    qd = s.diff(qofr, r) * rd
    L = simp(-A * qofr * qd ** 2 / N)
    ck.zero('point_transformed_action', L + 4 * A * rd ** 2 / (9 * N))
    dt = lambda v: s.diff(v, r) * rd + s.diff(v, rd) * rdd + s.diff(v, N) * Nd
    Er = simp(s.diff(L, r) - dt(s.diff(L, rd)))
    EN = simp(s.diff(L, N))
    ck.zero('constant_kinetic_radius_Euler', Er - 8 * A * (rdd / N - rd * Nd / N ** 2) / 9)
    ck.zero('positive_square_lapse_equation', EN - 4 * A * rd ** 2 / (9 * N ** 2))
    pr_expr = s.diff(L, rd)
    ck.zero('new_momentum', pr_expr + 8 * A * rd / (9 * N))
    C = simp((pr * rd - L).subs(rd, -9 * N * pr / (8 * A)) / N)
    ck.zero('constant_coefficient_quadratic_constraint', C + 9 * pr ** 2 / (16 * A))
    pqofr = s.Rational(3, 2) * r ** s.Rational(1, 3) * pr
    ck.zero('canonical_point_map', s.det(s.Matrix([[s.diff(qofr, r), s.diff(qofr, pr)], [s.diff(pqofr, r), s.diff(pqofr, pr)]])) - 1)
    ck.zero('constraint_coordinate_consistency', -pqofr ** 2 / (4 * A * qofr) - C)
    ck.zero('coordinate_change_does_not_regularize', s.diff(C, pr).subs(pr, 0))
    t, a, b, q0 = s.symbols('t a b q0', real=True)
    Ntest = 1 + 2 * t
    tau = t + t * t
    u = a + b * tau
    ck.zero('nonconstant_lapse_linear_solution', s.diff(u, t, 2) - s.diff(Ntest, t) * s.diff(u, t) / Ntest)
    ck.zero('nonconstant_lapse_second_order_constraint', A * q0 * s.diff(u, t) ** 2 / Ntest ** 2 - A * q0 * b * b)
    I = (1 - s.cos(2 * s.pi * t)) / (2 * s.pi)
    ck.zero('endpoint_preserving_example', [I.subs(t, 0), I.subs(t, 1), s.diff(I, t) - s.sin(2 * s.pi * t)])
    return dict(identities=ck.names, coordinate='r=q^(3/2)>0', L=L, Euler_r=Er, Euler_N=EN, momentum=pr_expr, constraint=C, canonical_inverse=dict(q=qofr, p_q=pqofr), conclusion='The zero-gradient quadratic constraint persists under a smooth invertible canonical point transformation.')

def derive_endpoints():
    """Fixed endpoint data and local linearized torus solutions."""
    ck = Identities()
    a, b, ti, tf, ui, uf = s.symbols('a b tau_i tau_f u_i u_f', real=True)
    duration = s.Symbol('T', positive=True)
    eq = [a + b * ti - ui, a + b * (ti + duration) - uf]
    solution = s.solve(eq, [a, b], dict=True)[0]
    ck.zero('endpoint_slope', solution[b] - (uf - ui) / duration)
    fixed = {ui: 0, uf: 0}
    ck.zero('fixed_Dirichlet_no_linear_shape_frozen_mode', [solution[a].subs(fixed), solution[b].subs(fixed)])
    ck.zero('equal_varying_boundary_values_integrable', solution[b].subs(uf, ui))
    ck.zero('equal_varying_boundary_offset', solution[a].subs(uf, ui) - ui)
    A, q0 = s.symbols('A q0', positive=True)
    obstruction = s.factor(A * q0 * solution[b] ** 2)
    ck.zero('unequal_endpoint_variation_obstruction', obstruction - A * q0 * (uf - ui) ** 2 / duration ** 2)
    N0 = s.Function('N0')
    xi = s.Function('xi')
    t = s.Symbol('t', real=True)
    gauge_lapse = s.diff(xi(t) * N0(t), t)
    ck.zero('gauge_lapse_total_derivative', gauge_lapse - s.diff(xi(t), t) * N0(t) - xi(t) * s.diff(N0(t), t))
    return dict(identities=ck.names, linear_solution_endpoint_coefficients=solution, second_order_endpoint_obstruction=obstruction, fixed_boundary_statement='If q at both endpoints is held at the same q0, u_i=u_f=0 already forces a=b=0 in the linear ODE. The spurious b mode is a feature of the local/initial-value linearized equation or of varying boundary data, not a surviving fixed-two-endpoint Dirichlet fluctuation.', variable_boundary_statement='Across exact solutions the two q boundary values must vary together. Their common variation a changes spatial volume and is not time gauge.', interval_statement='Endpoint-preserving time diffeomorphisms fix T=integral N dt; lapse profiles with the same T are gauge-related. If T is allowed to vary it is a separate interval parameter.')
